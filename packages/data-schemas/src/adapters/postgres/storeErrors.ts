/**
 * PostgreSQL store errors (`~/ports/storeErrors`; docs/postgres-port/PHASE4.md §3.6). Must not
 * import `mongoose`, `mongodb` or `bson`.
 *
 * A duplicate key is SQLSTATE 23505 (`unique_violation`), as `pg` reports it (`code: '23505'`,
 * with the violated index or constraint in `constraint`), or a `StoreDuplicateKeyError`, which
 * the collection primitive raises in its place once it has the written record
 * ({@link toStoreDuplicateKeyError}). The fields of the violated key come from a map of unique
 * index and constraint names to the record paths they cover: the schema descriptor's index map
 * (generated by F2/F3; empty until then), or the `keyValue` of a `StoreDuplicateKeyError`.
 */
import type { StoreErrors } from '~/ports/storeErrors';
import { StoreDuplicateKeyError } from '~/ports/storeErrors';

/** SQLSTATE `unique_violation`. */
export const UNIQUE_VIOLATION = '23505';

/** Unique index or constraint name → the record paths (fields) its key covers, in key order. */
export type UniqueConstraintFields = ReadonlyMap<string, ReadonlyArray<string>>;

/** The parts of a `pg` `DatabaseError` read here. */
interface PgErrorShape {
  code?: unknown;
  constraint?: unknown;
}

/** Whether `error` is PostgreSQL's unique violation (SQLSTATE 23505) as `pg` raises it. */
export function isUniqueViolation(error: unknown): boolean {
  return (
    typeof error === 'object' && error !== null && (error as PgErrorShape).code === UNIQUE_VIOLATION
  );
}

/** The violated index or constraint of a unique violation, when `pg` reports it. */
function constraintOf(error: unknown): string | undefined {
  const { constraint } = error as PgErrorShape;
  return typeof constraint === 'string' ? constraint : undefined;
}

/**
 * The store errors of a PostgreSQL backend whose unique indexes and constraints map to the
 * fields in `constraintFields`. A unique violation on a name the map lacks is still a duplicate
 * key; its fields are then unknown (`undefined`).
 */
export function createPostgresStoreErrors(
  constraintFields: UniqueConstraintFields = new Map(),
): StoreErrors {
  const isDuplicateKey = (error: unknown): boolean =>
    error instanceof StoreDuplicateKeyError || isUniqueViolation(error);

  return {
    isDuplicateKey,
    duplicateKeyFields: (error) => {
      if (error instanceof StoreDuplicateKeyError) {
        return error.keyValue ? Object.keys(error.keyValue) : undefined;
      }
      if (!isUniqueViolation(error)) {
        return undefined;
      }
      const constraint = constraintOf(error);
      const fields = constraint === undefined ? undefined : constraintFields.get(constraint);
      return fields ? [...fields] : undefined;
    },
  };
}

/**
 * The `StoreDuplicateKeyError` standing for `error`, a unique violation, with `keyValue` holding
 * the violated key's fields (from `constraintFields`) and the values `record` (the record the
 * write tried to store) has for them, read by dotted path. Without a known constraint the error
 * carries no `keyValue`. `cause` is `error`.
 */
export function toStoreDuplicateKeyError(
  error: unknown,
  constraintFields: UniqueConstraintFields,
  record?: Readonly<Record<string, unknown>>,
): StoreDuplicateKeyError {
  const constraint = constraintOf(error);
  const fields = constraint === undefined ? undefined : constraintFields.get(constraint);
  const message = error instanceof Error && error.message ? error.message : 'Duplicate key';
  if (!fields) {
    return new StoreDuplicateKeyError(message, { cause: error });
  }
  const keyValue: Record<string, unknown> = {};
  for (const field of fields) {
    keyValue[field] = record ? readPath(record, field) : undefined;
  }
  return new StoreDuplicateKeyError(message, { keyValue, cause: error });
}

/** The value at a dotted path of a record (`undefined` when missing; `null` stays `null`). */
function readPath(record: Readonly<Record<string, unknown>>, path: string): unknown {
  let current: unknown = record;
  for (const segment of path.split('.')) {
    if (typeof current !== 'object' || current === null) {
      return undefined;
    }
    current = (current as Record<string, unknown>)[segment];
  }
  return current;
}

/** The store errors of the PostgreSQL backend until the descriptor's index map exists (F3). */
export const postgresStoreErrors: StoreErrors = createPostgresStoreErrors();
