/**
 * The Kysely table types of a {@link SchemaDescriptor} (docs/postgres-port/PHASE4.md §5,
 * `db.generated.ts`): one interface per table and the `Database` interface mapping table names
 * to them, for the hand-written SQL of the store adapters. Column types are what the backend's
 * `pg` pool returns (`adapters/postgres/connection.ts`): `json`/`jsonb` read as text, `bytea` as
 * a `Buffer`, `timestamptz` as a `Date`. Must not import `mongoose`, `mongodb` or `bson`.
 */
import type { ColumnType, ColumnDescriptor, SchemaDescriptor } from './descriptor';
import { SchemaGenerationError } from './naming';

const TS_TYPES: Readonly<Record<ColumnType, string>> = {
  string: 'string',
  number: 'number',
  boolean: 'boolean',
  date: 'Timestamp',
  objectId: 'string',
  buffer: 'Buffer',
  objectIdOrString: 'string',
  integer: 'number',
  json: 'string',
  jsonb: 'string',
};

/** The TypeScript type of a column. */
export function columnTsType(column: ColumnDescriptor): string {
  let type = TS_TYPES[column.type];
  if (column.array) {
    type = column.type === 'date' ? 'Date[]' : `${type}[]`;
  }
  return column.nullable ? `${type} | null` : type;
}

/** `ConversationsCodeWorkspacesTable` for `conversations__codeWorkspaces`. */
export function tableInterfaceName(table: string): string {
  const words = table.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const name = words.map((word) => word[0].toUpperCase() + word.slice(1)).join('');
  return `${/^[0-9]/.test(name) ? `T${name}` : name}Table`;
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** The source of `db.generated.ts` for `descriptor`. */
export function emitKyselyTypes(descriptor: SchemaDescriptor): string {
  const names = new Map<string, string>();
  const blocks: string[] = [];
  for (const table of descriptor.tables) {
    const name = tableInterfaceName(table.name);
    const owner = names.get(name);
    if (owner !== undefined) {
      throw new SchemaGenerationError(
        `tables "${owner}" and "${table.name}" map to the same Kysely interface ${name}`,
      );
    }
    names.set(name, table.name);
    const columns = table.columns.map(
      (column) => `  ${propertyKey(column.name)}: ${columnTsType(column)};`,
    );
    blocks.push(
      `/** \`${table.name}\` (${table.kind}). */\nexport interface ${name} {\n${columns.join('\n')}\n}`,
    );
  }
  const database = descriptor.tables.map(
    (table) => `  ${propertyKey(table.name)}: ${tableInterfaceName(table.name)};`,
  );
  return [
    '/**',
    ' * Generated by the PostgreSQL schema generator (adapters/postgres/schema); do not edit.',
    ' * Must not import `mongoose`, `mongodb` or `bson`.',
    ' */',
    "import type { ColumnType } from 'kysely';",
    '',
    '/** A `timestamptz` column: read as a `Date`, written as a `Date` or an ISO string. */',
    'export type Timestamp = ColumnType<Date, Date | string, Date | string>;',
    '',
    ...blocks.flatMap((block) => [block, '']),
    '/** Every table of the PostgreSQL schema. */',
    `export interface Database {\n${database.join('\n')}\n}`,
    '',
  ].join('\n');
}
