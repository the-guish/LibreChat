/**
 * The migration modules the generator writes (docs/postgres-port/PHASE4.md §5, `npm run
 * db:generate`): the statements of the snapshot diff as a checked-in TypeScript module under
 * `adapters/postgres/migrations/`, and the static list of every migration in `index.ts` (tsdown
 * bundles the package, so the migrator cannot read a folder at run time). Pure string building.
 * Must not import `mongoose`, `mongodb` or `bson`.
 *
 * Kysely applies the pending migrations in one transaction, and `CREATE INDEX CONCURRENTLY`
 * cannot run in one. So a migration never builds an index on an existing large table (§5,
 * `largeTables` in `overrides.ts`): the diff's `CONCURRENTLY` index builds are left out of the
 * module and listed in its header, and the post-migration step of the migrator
 * (`buildDeferredPostgresIndexes` in `migrator.ts`) builds every index the descriptor declares on
 * a large table and the database lacks, `CONCURRENTLY`, outside any transaction. Dropping such an
 * index stays in the migration (`DROP INDEX IF EXISTS`: quick, and the index may never have been
 * built). Indexes of a new table, large or not, are built in the migration: the table is empty.
 */
import type { SchemaDescriptor } from './descriptor';
import type { SchemaChange } from './diff';
import { diffSchemaDescriptors, emitMigrationDdl } from './diff';
import { HELPER_FUNCTIONS_DDL } from './functions';
import { emitPreludeDdl } from './emitDdl';
import { quoteIdentifier } from './naming';

/** The name of the first migration, which creates the whole schema. */
export const INITIAL_MIGRATION_NAME = '0001_initial';

/** What a migration does. */
export interface PlannedMigration {
  /** The changes from the previous snapshot. */
  changes: SchemaChange[];
  /** The statements the migration runs, in order, inside the migration transaction. */
  statements: string[];
  /** Indexes on large tables left to the post-migration step (built `CONCURRENTLY`). */
  deferredIndexes: string[];
}

/**
 * The migration from `previous` (the snapshot of the latest migration; `null` before the first)
 * to `next`. The first migration also creates the `lc_object_id` domain and the `lc_*` helper
 * functions. Throws `SchemaGenerationError` for a change that needs a hand-written migration.
 */
export function planMigration(
  previous: SchemaDescriptor | null,
  next: SchemaDescriptor,
): PlannedMigration {
  const changes = diffSchemaDescriptors(previous, next);
  const statements = previous === null ? [...emitPreludeDdl(), ...HELPER_FUNCTIONS_DDL] : [];
  const deferredIndexes: string[] = [];
  for (const change of changes) {
    if (change.kind === 'createIndex' && change.concurrently) {
      deferredIndexes.push(change.index.name);
    } else if (change.kind === 'dropIndex' && change.concurrently) {
      statements.push(`DROP INDEX IF EXISTS ${quoteIdentifier(change.index.name)}`);
    } else {
      statements.push(...emitMigrationDdl([change]).map((statement) => statement.sql));
    }
  }
  return { changes, statements, deferredIndexes };
}

/** `name` as the `<YYYYMMDDHHmm>_<slug>` of a migration written at `now` (UTC). */
export function migrationName(slug: string, now: Date): string {
  const cleaned = slug
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!cleaned) {
    throw new Error(`A migration needs a slug of letters or digits, got "${slug}"`);
  }
  const pad = (value: number) => String(value).padStart(2, '0');
  const stamp =
    `${now.getUTCFullYear()}${pad(now.getUTCMonth() + 1)}${pad(now.getUTCDate())}` +
    `${pad(now.getUTCHours())}${pad(now.getUTCMinutes())}`;
  return `${stamp}_${cleaned}`;
}

/** Whether `name` is a migration module name (`0001_initial` or `<YYYYMMDDHHmm>_<slug>`). */
export function isMigrationName(name: string): boolean {
  return name === INITIAL_MIGRATION_NAME || /^[0-9]{12}_[a-z0-9]+(?:_[a-z0-9]+)*$/.test(name);
}

/** `text` as the body of a template literal. */
function templateLiteral(text: string): string {
  return `\`${text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``;
}

/** `items` as ` * ` comment lines of at most about 100 characters. */
function commentList(items: readonly string[]): string[] {
  const lines: string[] = [];
  let line = ' *  ';
  for (const item of items) {
    const next = `${line} ${item}`;
    if (next.length > 98 && line.trim() !== '*') {
      lines.push(line.trimEnd());
      line = ` *   ${item}`;
    } else {
      line = next;
    }
  }
  lines.push(line.trimEnd());
  return lines;
}

/** The source of the migration module `name`. */
export function emitMigrationModule(name: string, migration: PlannedMigration): string {
  const header = [
    '/**',
    ` * PostgreSQL migration \`${name}\`: generated by \`npm run db:generate\` from the snapshot diff`,
    ' * (docs/postgres-port/PHASE4.md §5). Checked in as generated; never changed afterwards. Must not',
    ' * import `mongoose`, `mongodb` or `bson`.',
  ];
  if (name === INITIAL_MIGRATION_NAME) {
    header.push(
      ' *',
      ' * The whole schema: the `lc_object_id` domain, the `lc_*` helper functions, every table and',
      ' * every index.',
    );
  }
  if (migration.deferredIndexes.length > 0) {
    header.push(
      ' *',
      ' * Indexes on large tables built `CONCURRENTLY` by the post-migration step rather than here:',
      ...commentList(migration.deferredIndexes),
    );
  }
  header.push(' */');
  return [
    ...header,
    "import { sql } from 'kysely';",
    "import type { Kysely } from 'kysely';",
    '',
    '/** The statements of this migration, run in order inside the migration transaction. */',
    'export const statements: readonly string[] = [',
    ...migration.statements.map((statement) => `  ${templateLiteral(statement)},`),
    '];',
    '',
    '/** Applies this migration. */',
    'export async function up(db: Kysely<unknown>): Promise<void> {',
    '  for (const statement of statements) {',
    '    await sql.raw(statement).execute(db);',
    '  }',
    '}',
    '',
  ].join('\n');
}

/** The identifier `index.ts` imports the migration `name` as. */
function migrationIdentifier(name: string): string {
  const words = name.split('_');
  return `m${words[0]}${words
    .slice(1)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join('')}`;
}

/** The source of `migrations/index.ts` listing the migrations `names`. */
export function emitMigrationIndex(names: readonly string[]): string {
  const sorted = [...names].sort();
  for (const name of sorted) {
    if (!isMigrationName(name)) {
      throw new Error(`"${name}" is not a migration name (0001_initial or <YYYYMMDDHHmm>_<slug>)`);
    }
  }
  /** Value imports from local modules, longest line first (the repository's import order). */
  const imports = sorted
    .map((name) => `import * as ${migrationIdentifier(name)} from './${name}';`)
    .map((line, position) => ({ line, position }))
    .sort((a, b) => b.line.length - a.line.length || a.position - b.position)
    .map(({ line }) => line);
  return [
    '/**',
    ' * The PostgreSQL migrations, in code (docs/postgres-port/PHASE4.md §5): every migration module',
    ' * imported statically and listed here under its name (`0001_initial`, then',
    ' * `<YYYYMMDDHHmm>_<slug>`), because tsdown bundles the package and a migration folder read at run',
    ' * time would not exist in `dist`. Generated by `npm run db:generate` (`schema/migrationModule.ts`),',
    ' * which writes the new module and this list and never changes a module already checked in; do not',
    ' * edit. Must not import `mongoose`, `mongodb` or `bson`.',
    ' */',
    "import type { Migration } from 'kysely';",
    ...imports,
    '',
    '/** Every migration of the PostgreSQL schema, by name; applied in name order. */',
    'export const POSTGRES_MIGRATIONS: Readonly<Record<string, Migration>> = Object.freeze({',
    ...sorted.map(
      (name) => `  ${JSON.stringify(name).replace(/"/g, "'")}: ${migrationIdentifier(name)},`,
    ),
    '});',
    '',
  ].join('\n');
}
