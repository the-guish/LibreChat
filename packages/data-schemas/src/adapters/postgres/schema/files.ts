/**
 * The checked-in output of the PostgreSQL schema generator (docs/postgres-port/PHASE4.md §5) and
 * how it is kept current: `npm run db:generate` writes it, drift spec 1 (`drift.spec.ts`) and
 * `db:generate --check` compare it with a fresh generation. Must not import `mongoose`, `mongodb`
 * or `bson` (the descriptor is passed in; `generate.ts` builds it).
 *
 * - `schema/descriptor.generated.ts`: the descriptor the adapter reads at run time;
 * - `schema/db.generated.ts`: the Kysely table types;
 * - `schema/snapshot.json`: the descriptor as of the latest migration;
 * - `migrations/<name>.ts`: a new migration when the descriptor differs from the snapshot
 *   (`0001_initial` when there is no snapshot yet), and `migrations/index.ts` listing every
 *   migration module of the folder.
 *
 * A migration already checked in is never rewritten.
 */
import fs from 'node:fs';
import path from 'node:path';
import type { SchemaDescriptor } from './descriptor';
import {
  migrationName,
  planMigration,
  isMigrationName,
  emitMigrationIndex,
  emitMigrationModule,
  INITIAL_MIGRATION_NAME,
} from './migrationModule';
import { emitKyselyTypes } from './emitKysely';

/** Where the generated files live. */
export interface SchemaFilePaths {
  /** `adapters/postgres/schema`: `descriptor.generated.ts`, `db.generated.ts`, `snapshot.json`. */
  schemaDir: string;
  /** `adapters/postgres/migrations`: the migration modules and `index.ts`. */
  migrationsDir: string;
}

/** The generated file names inside {@link SchemaFilePaths.schemaDir}. */
export const SCHEMA_FILES = {
  descriptor: 'descriptor.generated.ts',
  kysely: 'db.generated.ts',
  snapshot: 'snapshot.json',
} as const;

/** One file the generator writes. */
export interface SchemaFileWrite {
  path: string;
  content: string;
}

/** What `db:generate` writes for a descriptor. */
export interface SchemaFilesPlan {
  writes: SchemaFileWrite[];
  /** The new migration's name, when the descriptor differs from the snapshot. */
  migration?: string;
  /** Indexes the new migration leaves to the post-migration step. */
  deferredIndexes: string[];
}

/** The source of `descriptor.generated.ts`. */
export function emitDescriptorModule(descriptor: SchemaDescriptor): string {
  return [
    '/**',
    ' * Generated by the PostgreSQL schema generator (adapters/postgres/schema); do not edit.',
    ' * Must not import `mongoose`, `mongodb` or `bson`.',
    ' */',
    "import type { SchemaDescriptor } from './descriptor';",
    '',
    `export const SCHEMA_DESCRIPTOR: SchemaDescriptor = ${JSON.stringify(descriptor, null, 2)};`,
    '',
  ].join('\n');
}

/** The text of `snapshot.json`. */
export function emitSnapshot(descriptor: SchemaDescriptor): string {
  return `${JSON.stringify(descriptor, null, 2)}\n`;
}

function readText(file: string): string | undefined {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      return undefined;
    }
    throw error;
  }
}

/** The migration modules checked in under `migrationsDir`, by name (sorted). */
export function listMigrationModules(migrationsDir: string): string[] {
  const names = fs
    .readdirSync(migrationsDir)
    .filter(
      (file) => file.endsWith('.ts') && file !== 'index.ts' && !/\.(spec|test)\.ts$/.test(file),
    )
    .map((file) => file.slice(0, -'.ts'.length))
    .sort();
  for (const name of names) {
    if (!isMigrationName(name)) {
      throw new Error(
        `${path.join(migrationsDir, `${name}.ts`)} is not named like a migration (0001_initial or <YYYYMMDDHHmm>_<slug>)`,
      );
    }
  }
  return names;
}

/** The snapshot of the latest migration, or `null` when none is checked in. */
export function readSnapshot(paths: SchemaFilePaths): SchemaDescriptor | null {
  const text = readText(path.join(paths.schemaDir, SCHEMA_FILES.snapshot));
  return text === undefined ? null : (JSON.parse(text) as SchemaDescriptor);
}

/**
 * The files `db:generate` writes for `descriptor` (a freshly generated one): the three generated
 * files, and a new migration (named `slug`, stamped `now`) plus the migration list when the
 * descriptor differs from the snapshot. Throws when the change needs a hand-written migration.
 */
export function planSchemaFiles(
  descriptor: SchemaDescriptor,
  paths: SchemaFilePaths,
  options: { slug?: string; now?: Date } = {},
): SchemaFilesPlan {
  const previous = readSnapshot(paths);
  const existing = listMigrationModules(paths.migrationsDir);
  if (previous === null && existing.length > 0) {
    throw new Error(
      `${SCHEMA_FILES.snapshot} is missing while migrations exist (${existing.join(', ')}); restore it from git`,
    );
  }
  const writes: SchemaFileWrite[] = [
    {
      path: path.join(paths.schemaDir, SCHEMA_FILES.descriptor),
      content: emitDescriptorModule(descriptor),
    },
    { path: path.join(paths.schemaDir, SCHEMA_FILES.kysely), content: emitKyselyTypes(descriptor) },
    { path: path.join(paths.schemaDir, SCHEMA_FILES.snapshot), content: emitSnapshot(descriptor) },
  ];
  const migration = planMigration(previous, descriptor);
  let name: string | undefined;
  const names = [...existing];
  if (previous === null || migration.changes.length > 0) {
    name =
      previous === null
        ? INITIAL_MIGRATION_NAME
        : migrationName(options.slug ?? 'schema', options.now ?? new Date());
    if (names.includes(name)) {
      throw new Error(`Migration ${name} already exists; pass another name`);
    }
    names.push(name);
    writes.push({
      path: path.join(paths.migrationsDir, `${name}.ts`),
      content: emitMigrationModule(name, migration),
    });
  }
  writes.push({
    path: path.join(paths.migrationsDir, 'index.ts'),
    content: emitMigrationIndex(names),
  });
  return { writes, migration: name, deferredIndexes: name ? migration.deferredIndexes : [] };
}

/** The planned files whose content differs from what is on disk (new files included). */
export function findOutOfDateSchemaFiles(plan: SchemaFilesPlan): string[] {
  return plan.writes
    .filter((write) => readText(write.path) !== write.content)
    .map((write) => write.path);
}
