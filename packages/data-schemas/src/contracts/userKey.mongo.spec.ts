/** Test credentials, before `~/crypto` loads (side-effect import: keep it first). */
import './credentialsEnv';
import { MongoMemoryServer } from 'mongodb-memory-server';
import type { MongoContractEngine } from '~/adapters/mongo/contractHarness';
import { createMongoContractHarness } from '~/adapters/mongo/contractHarness';
import { describeUserKeyContract } from './userKey.contract';

/** The user key store contract on MongoDB; the PostgreSQL run comes with its S unit. */
let server: MongoMemoryServer;
const engine: MongoContractEngine = {
  async connect() {
    server = await MongoMemoryServer.create();
    return server.getUri();
  },
  async release() {
    await server.stop();
  },
};

describeUserKeyContract(createMongoContractHarness(engine));
